/**
 * Mission Control → Desktop question surface (focusable window).
 *
 * The widget stays a one-click, non-focusable inspection; asking a question happens here. The
 * panel always shows the three-step model before the controls — bring the target app forward,
 * inspect once from the widget, then ask about that local snapshot — and never captures on page
 * open or refresh. A preview discloses the exact prompt, provider, model, source age, partial
 * flags, and expiry; only the explicit "Send this evidence to OpenAI" button confirms, and a
 * failed or consumed confirmation always requires a fresh preview.
 */
import { useEffect, useId, useRef, useSyncExternalStore } from 'react';
import {
  createDesktopQuestionClient,
  desktopQuestionExpiry,
  desktopQuestionSourceAge,
  DESKTOP_QUESTION_MAX_CHARS,
  type DesktopQuestionAnswer,
  type DesktopQuestionClient,
  type DesktopQuestionPreview,
  type DesktopQuestionSource,
  type DesktopQuestionState,
} from './desktop-question-client';

function SourceSummary({ source, label }: { source: DesktopQuestionSource; label: string }) {
  const partial = source.quality === 'partial' || source.truncated;
  return (
    <dl className="desktop-question-meta" aria-label={label}>
      <div>
        <dt>Application</dt>
        <dd>{source.application.name} — {source.application.bundleId}{source.application.identityTruncated ? ' · identity truncated' : ''}</dd>
      </div>
      <div>
        <dt>Window</dt>
        <dd>{source.window.title.trim().length > 0 ? source.window.title : '(untitled)'} — {source.window.role}{source.window.titleTruncated ? ' · title truncated' : ''}</dd>
      </div>
      <div>
        <dt>Snapshot</dt>
        <dd>{partial ? `Partial snapshot${source.truncations.length > 0 ? ` (${source.truncations.join(', ')})` : ''}` : 'Complete bounded snapshot'} · {source.rows.length} evidence rows shown</dd>
      </div>
    </dl>
  );
}

function EvidenceList({ source, label }: { source: DesktopQuestionSource; label: string }) {
  if (source.rows.length === 0) return null;
  return (
    <ul className="desktop-question-evidence" aria-label={label}>
      {source.rows.map((row) => (
        <li key={row.evidenceId}>
          <span className="desktop-question-evidence-id">[{row.number}] {row.evidenceId}</span>
          <span className="desktop-question-evidence-role">{row.role}{row.truncated ? ' · truncated' : ''}</span>
          {row.label !== null && <p>label: {row.label}</p>}
          {row.value !== null && <p>value: {row.value}</p>}
        </li>
      ))}
    </ul>
  );
}

function AnswerBlock({ answer }: { answer: DesktopQuestionAnswer }) {
  const usage = answer.inputTokens !== null && answer.outputTokens !== null
    ? `${answer.inputTokens} input · ${answer.outputTokens} output tokens reported`
    : 'Token usage was not reported, so it stays unknown — not zero';
  return (
    <section className="desktop-question-answer" role="status" aria-label="Model-generated answer">
      <span className="signal-overline">MODEL-GENERATED ANSWER · {answer.model}</span>
      <p className="desktop-question-answer-text">{answer.answer}</p>
      <p className="desktop-question-disclosure">
        This answer was generated by {answer.model}. Its citations were not verified against the snapshot, so treat it as
        unverified and check the evidence below. No screenshot or OCR was used.
      </p>
      <SourceSummary source={answer.evidence} label="Snapshot this answer was grounded in" />
      <EvidenceList source={answer.evidence} label="Snapshot evidence rows" />
      <p className="signal-muted">{usage}. Cost is not estimated for this path, so no dollar amount is shown.</p>
    </section>
  );
}

function PreviewBlock({ preview, state, client, nowMs }: {
  preview: DesktopQuestionPreview;
  state: DesktopQuestionState;
  client: DesktopQuestionClient;
  nowMs: number;
}) {
  const confirming = state.phase === 'confirming';
  return (
    <section className="desktop-question-preview" aria-label="Review the exact prompt before sending" aria-busy={confirming}>
      <span className="signal-overline">REVIEW BEFORE SENDING</span>
      <p className="desktop-question-preview-lead">
        This is the exact prompt and evidence that would be sent to OpenAI. Reviewing it sends nothing.
      </p>
      <dl className="desktop-question-meta">
        <div><dt>Provider</dt><dd>OpenAI · {preview.model}</dd></div>
        <div><dt>Source age</dt><dd>{desktopQuestionSourceAge(preview.evidence.observedAtMs, nowMs)}</dd></div>
        <div><dt>Expiry</dt><dd>{desktopQuestionExpiry(preview.expiresAtMs, nowMs)}</dd></div>
      </dl>
      <SourceSummary source={preview.evidence} label="Snapshot this prompt uses" />
      <label className="project-question-label" htmlFor="desktop-question-prompt">Exact prompt that will be sent</label>
      <pre id="desktop-question-prompt" className="desktop-question-prompt">{preview.prompt}</pre>
      <EvidenceList source={preview.evidence} label="Snapshot evidence included in this prompt" />
      <div className="desktop-question-actions">
        <button
          type="button"
          className="signal-primary"
          aria-busy={confirming}
          disabled={confirming}
          onClick={() => void client.confirm()}
        >
          {confirming ? 'Sending the previewed evidence…' : 'Send this evidence to OpenAI'}
        </button>
        <button type="button" className="signal-secondary" disabled={confirming} onClick={() => void client.cancelPreview()}>
          Cancel
        </button>
      </div>
      <p className="signal-muted">
        Sending uses a one-time permission grant for this exact evidence. Canceling discards it; nothing is sent until you
        choose "Send this evidence to OpenAI".
      </p>
    </section>
  );
}

export function DesktopQuestionPanel({ client, onOpenWork, now = Date.now }: {
  client?: DesktopQuestionClient;
  onOpenWork: () => void;
  now?: () => number;
}) {
  const questionId = useId();
  const controllerRef = useRef<DesktopQuestionClient | null>(null);
  const ownedRef = useRef(false);
  if (controllerRef.current === null) {
    controllerRef.current = client ?? createDesktopQuestionClient();
    ownedRef.current = client === undefined;
  }
  const controller = controllerRef.current;
  const state = useSyncExternalStore(controller.subscribe, controller.getSnapshot, controller.getSnapshot);
  const nowMs = now();

  useEffect(() => {
    void controller.loadContext();
    return () => { if (ownedRef.current) controller.dispose(); };
  }, [controller]);

  const busy = state.phase === 'previewing' || state.phase === 'confirming';
  const context = state.context;
  const snapshotReady = context.kind === 'ready' && context.snapshot !== null;
  const questionReady = state.question.trim().length > 0 && state.question.trim().length <= DESKTOP_QUESTION_MAX_CHARS;
  const showQuestionForm = context.kind === 'ready' && state.preview === null;

  return (
    <section className="signal-card desktop-question" aria-label="Ask about the latest window snapshot" aria-busy={busy}>
      <div className="signal-card-head">
        <div>
          <h2>Ask about the latest snapshot</h2>
          <p>Grounded questions about the last window you inspected. The widget only reads; asking happens here in Mission Control.</p>
        </div>
      </div>
      <ol className="desktop-question-steps">
        <li>Bring the app you want to ask about to the foreground.</li>
        <li>Click <strong>Inspect window</strong> in the widget once — a local Accessibility snapshot is kept in memory.</li>
        <li>Return here, refresh the context if needed, then ask your question about that snapshot.</li>
      </ol>
      <p className="signal-muted" role="note">
        Opening or refreshing this page never captures anything. The widget never sends. Only "Send this evidence to OpenAI"
        below reaches the API, after you review the exact prompt.
      </p>

      {context.kind === 'loading' && <p className="desktop-question-status" role="status">Reading the active Work project and the latest local snapshot…</p>}
      {context.kind === 'blocked' && (
        <p className="desktop-question-status" role="status">
          {context.activeProjects === 0
            ? 'No active Work project. Connect one in Work; this page never guesses scope from window titles.'
            : `${context.activeProjects} projects are active. Choose one in Work; this page uses your remembered selection.`}
          {' '}
          <button type="button" className="text-button" onClick={onOpenWork}>Open Work ↗</button>
        </p>
      )}
      {context.kind === 'unavailable' && (
        <p className="signal-feedback" role="alert">
          {context.message}{' '}
          <button type="button" className="text-button" onClick={() => void controller.loadContext()}>Try again</button>
        </p>
      )}
      {context.kind === 'error' && (
        <p className="signal-feedback" role="alert">
          {context.message}{' '}
          <button type="button" className="text-button" onClick={() => void controller.loadContext()}>Try again</button>
        </p>
      )}
      {context.kind === 'ready' && context.snapshot === null && (
        <p className="desktop-question-status" role="status">
          No recent local snapshot for {context.projectLabel}. Bring the target app to the foreground, click "Inspect window"
          in the widget, then refresh this context.{' '}
          <button type="button" className="signal-secondary" disabled={busy} onClick={() => void controller.loadContext()}>Refresh context</button>
        </p>
      )}
      {context.kind === 'ready' && context.snapshot !== null && (
        <p className="desktop-question-status" role="status">
          Project: {context.projectLabel} · snapshot from {desktopQuestionSourceAge(context.snapshot.observedAtMs, nowMs)} ·{' '}
          {desktopQuestionExpiry(context.snapshot.expiresAtMs, nowMs)}{' '}
          <button type="button" className="text-button" disabled={busy} onClick={() => void controller.loadContext()}>Refresh context</button>
        </p>
      )}

      {state.error !== null && (
        <p className="signal-feedback desktop-question-error" role="alert">
          {state.error.message}{state.error.requiresNewPreview ? ' The preview is used up, so retry with a new preview.' : ''}
        </p>
      )}

      {showQuestionForm && (
        <div className="desktop-question-form">
          <label className="project-question-label" htmlFor={questionId}>Your question about this snapshot</label>
          <textarea
            id={questionId}
            className="project-question"
            value={state.question}
            maxLength={DESKTOP_QUESTION_MAX_CHARS}
            placeholder="What does this window say about the retry budget?"
            disabled={busy}
            onChange={(event) => controller.setQuestion(event.currentTarget.value)}
          />
          <p className="signal-muted">
            {state.question.trim().length}/{DESKTOP_QUESTION_MAX_CHARS} characters. Answers are grounded only in the snapshot
            rows, and no screenshot or OCR is used.
          </p>
          <div className="desktop-question-actions">
            <button
              type="button"
              className="signal-primary"
              aria-busy={state.phase === 'previewing'}
              disabled={busy || !snapshotReady || !questionReady}
              onClick={() => void controller.preview()}
            >
              {state.phase === 'previewing' ? 'Preparing preview…' : 'Preview'}
            </button>
          </div>
          <p className="signal-muted">Previewing builds the exact prompt locally and sends nothing to any API.</p>
        </div>
      )}

      {state.preview !== null && (
        <PreviewBlock preview={state.preview} state={state} client={controller} nowMs={nowMs} />
      )}
      {state.answer !== null && <AnswerBlock answer={state.answer} />}
    </section>
  );
}
