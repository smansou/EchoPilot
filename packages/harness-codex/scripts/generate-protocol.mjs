#!/usr/bin/env node
/**
 * Regenerates `schema/` and `src/generated/protocol.ts` from the installed, tested Codex CLI:
 *
 *   codex --version                                    → pinned supported version
 *   codex app-server generate-json-schema --out schema → the pinned app-server JSON Schema bundle
 *
 * `src/generated/protocol.ts` is the small, reviewable projection of that bundle the adapter is
 * allowed to rely on: client request/notification methods, server notification/request methods,
 * thread item discriminants, and approval decision values. Nothing in the adapter hardcodes a
 * method name or decision string that is not first verified against this generated projection.
 *
 * Usage:
 *   node scripts/generate-protocol.mjs           # regenerate
 *   node scripts/generate-protocol.mjs --check   # fail if the checked-in projection is stale
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = join(packageRoot, 'schema');
const outputPath = join(packageRoot, 'src', 'generated', 'protocol.ts');
const checkOnly = process.argv.slice(2).includes('--check');

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

function runCodex(args) {
  const result = spawnSync('codex', args, { encoding: 'utf8' });
  if (result.error) fail(`Unable to run \`codex ${args.join(' ')}\`: ${result.error.message}`);
  if (result.status !== 0) {
    fail(`\`codex ${args.join(' ')}\` exited with ${String(result.status)}:\n${result.stderr ?? ''}`);
  }
  return result.stdout ?? '';
}

function get(value, path) {
  let current = value;
  for (const key of path) {
    if (current === null || typeof current !== 'object' || !(key in current)) {
      fail(`Generated schema is missing ${path.join('.')}`);
    }
    current = current[key];
  }
  return current;
}

function readSchema(relativePath) {
  return JSON.parse(readFileSync(join(schemaDir, relativePath), 'utf8'));
}

function methodNames(schema) {
  const entries = get(schema, ['oneOf']);
  if (!Array.isArray(entries)) fail('Expected a oneOf union of JSON-RPC messages');
  return entries.map((entry) => {
    const method = entry?.properties?.method?.enum?.[0];
    if (typeof method !== 'string') fail('Every JSON-RPC message variant must name its method');
    return method;
  });
}

function collectStringEnums(node, found) {
  if (node === null || typeof node !== 'object') return;
  if (Array.isArray(node.enum) && node.enum.every((value) => typeof value === 'string')) {
    for (const value of node.enum) found.add(value);
  }
  for (const value of Object.values(node)) collectStringEnums(value, found);
}

const versionText = runCodex(['--version']);
const versionMatch = /codex-cli (\d+\.\d+\.\d+[^\s]*)/.exec(versionText);
if (versionMatch === null) fail(`Could not read the pinned version from \`codex --version\`: ${versionText.trim()}`);
const cliVersion = versionMatch[1];

mkdirSync(schemaDir, { recursive: true });
runCodex(['app-server', 'generate-json-schema', '--out', schemaDir]);

const clientRequests = methodNames(readSchema('ClientRequest.json'));
const clientNotifications = methodNames(readSchema('ClientNotification.json'));
const serverNotifications = methodNames(readSchema('ServerNotification.json'));
const serverRequests = methodNames(readSchema('ServerRequest.json'));
const threadItems = get(readSchema('codex_app_server_protocol.v2.schemas.json'), ['definitions', 'ThreadItem', 'oneOf'])
  .map((entry) => entry?.properties?.type?.enum?.[0])
  .filter((value) => typeof value === 'string');
if (threadItems.length === 0) fail('Expected discriminated thread item types in the generated schema bundle');

const approvalDecisions = new Set();
collectStringEnums(readSchema('CommandExecutionRequestApprovalResponse.json'), approvalDecisions);

const projection = {
  generator: 'codex app-server generate-json-schema',
  cliVersion,
  clientRequests,
  clientNotifications,
  serverNotifications,
  serverRequests,
  threadItemTypes: threadItems,
  approvalDecisions: [...approvalDecisions].sort(),
};

const source = `/**
 * GENERATED FILE — do not edit by hand.
 *
 * Projection of the JSON Schema bundle generated by the installed, tested Codex app-server
 * (\`codex app-server generate-json-schema\`, codex-cli ${cliVersion}). Regenerate with
 * \`node scripts/generate-protocol.mjs\`; verify with \`--check\`.
 */
export const generatedProtocol = ${JSON.stringify(projection, null, 2)} as const;
`;

if (checkOnly) {
  let existing = '';
  try {
    existing = readFileSync(outputPath, 'utf8');
  } catch (error) {
    fail(`Missing generated projection at ${outputPath}: ${error.message}`);
  }
  if (existing !== source) {
    fail('Generated protocol projection is stale: re-run `node scripts/generate-protocol.mjs`');
  }
  process.stdout.write(`Generated protocol projection matches codex-cli ${cliVersion}\n`);
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, source);
  process.stdout.write(`Wrote ${outputPath} for codex-cli ${cliVersion}\n`);
}
